import Foundation
import CryptoKit

/// libgcrypt keygrip computation for NIST P-256 public keys.
///
/// libgcrypt (`_gcry_ecc_compute_keygrip` in `cipher/ecc.c`) computes the
/// keygrip as SHA-1 over the concatenation of the canonical domain parameters
/// and the public point — never the curve *name*. Each parameter is emitted as
/// a canonical S-expression token `(1:<name><len>:<value>)` in the fixed order
/// p, a, b, g, n, q. The cofactor h is deliberately excluded.
public enum Keygrip {
    // NIST P-256 (SEC2 secp256r1) domain parameters, big-endian, in the fixed
    // 32-byte / 65-byte forms libgcrypt stores.
    private static let p = Data([
        0xFF,0xFF,0xFF,0xFF,0x00,0x00,0x00,0x01,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
        0x00,0x00,0x00,0x00,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF])
    private static let a = Data([
        0xFF,0xFF,0xFF,0xFF,0x00,0x00,0x00,0x01,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
        0x00,0x00,0x00,0x00,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFC])
    private static let b = Data([
        0x5A,0xC6,0x35,0xD8,0xAA,0x3A,0x93,0xE7,0xB3,0xEB,0xBD,0x55,0x76,0x98,0x86,0xBC,
        0x65,0x1D,0x06,0xB0,0xCC,0x53,0xB0,0xF6,0x3B,0xCE,0x3C,0x3E,0x27,0xD2,0x60,0x4B])
    private static let g = Data([
        0x04,
        0x6B,0x17,0xD1,0xF2,0xE1,0x2C,0x42,0x47,0xF8,0xBC,0xE6,0xE5,0x63,0xA4,0x40,0xF2,
        0x77,0x03,0x7D,0x81,0x2D,0xEB,0x33,0xA0,0xF4,0xA1,0x39,0x45,0xD8,0x98,0xC2,0x96,
        0x4F,0xE3,0x42,0xE2,0xFE,0x1A,0x7F,0x9B,0x8E,0xE7,0xEB,0x4A,0x7C,0x0F,0x9E,0x16,
        0x2B,0xCE,0x33,0x57,0x6B,0x31,0x5E,0xCE,0xCB,0xB6,0x40,0x68,0x37,0xBF,0x51,0xF5])
    private static let n = Data([
        0xFF,0xFF,0xFF,0xFF,0x00,0x00,0x00,0x00,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,
        0xBC,0xE6,0xFA,0xAD,0xA7,0x17,0x9E,0x84,0xF3,0xB9,0xCA,0xC2,0xFC,0x63,0x25,0x51])

    /// Compute the 20-byte keygrip for a P-256 public point.
    public static func p256(point: ECPoint) -> Data {
        let q = point.uncompressed // 0x04 || X || Y
        var buf = Data()
        appendToken(&buf, name: "p", value: p)
        appendToken(&buf, name: "a", value: a)
        appendToken(&buf, name: "b", value: b)
        appendToken(&buf, name: "g", value: g)
        appendToken(&buf, name: "n", value: n)
        appendToken(&buf, name: "q", value: q)
        return Data(Insecure.SHA1.hash(data: buf))
    }

    /// Append `(1:<name><len>:<value>)` in canonical S-expression form.
    private static func appendToken(_ buf: inout Data, name: String, value: Data) {
        buf.append(contentsOf: "(1:\(name)\(value.count):".utf8)
        buf.append(value)
        buf.append(0x29) // ')'
    }
}
